#!/usr/bin/env bash
# Generate local Authelia secrets and a dev user database.
#
# Mirrors infrastructure/scripts/local/certs.sh: local-only material, generated on demand and
# gitignored, never committed. Production gets both from Ansible + vault.
#
# Usage: bash infrastructure/scripts/local/authelia-dev-init.sh <authelia-dir> <dev-email> <dev-password>
set -euo pipefail

usage="Usage: authelia-dev-init.sh <authelia-dir> <dev-email> <dev-password>"
AUTHELIA_DIR="${1:?$usage}"
DEV_EMAIL="${2:?$usage}"
DEV_PASSWORD="${3:?$usage}"
IMAGE="authelia/authelia:4.39.28"

SECRETS_DIR="${AUTHELIA_DIR}/secrets"
USERS_FILE="${AUTHELIA_DIR}/users_database.yml"

mkdir -p "${SECRETS_DIR}"

for name in session storage_encryption; do
  target="${SECRETS_DIR}/${name}"
  if [ ! -s "${target}" ]; then
    echo "==> Generating ${name}..."
    openssl rand -hex 32 > "${target}"
    chmod 600 "${target}"
  fi
done

if [ -s "${USERS_FILE}" ]; then
  echo "==> ${USERS_FILE} exists — leaving it alone."
  exit 0
fi

echo "==> Hashing the dev password (argon2id)..."
# Authelia's own hasher, so parameters always match configuration.yml.
  # --memory is KiB here, matching the config's `memory:` key exactly.
HASH="$(docker run --rm "${IMAGE}" \
  authelia crypto hash generate argon2 \
    --variant argon2id --iterations 3 --memory 32768 --parallelism 2 \
    --password "${DEV_PASSWORD}" \
  | sed 's/^Digest: //')"

cat > "${USERS_FILE}" <<YML
# Local development only — generated by infrastructure/scripts/local/authelia-dev-init.sh.
# Production renders this from vault; see the platform Ansible role.
users:
  dev:
    disabled: false
    displayname: 'Dev'
    password: '${HASH}'
    email: '${DEV_EMAIL}'
    groups: ['admin']
YML
chmod 600 "${USERS_FILE}"

echo ""
echo "Done — dev login: ${DEV_EMAIL} / ${DEV_PASSWORD}"
